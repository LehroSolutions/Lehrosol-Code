'use strict';
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const net = require('node:net');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const option = (name) => { const i = process.argv.indexOf(name); return i < 0 ? null : process.argv[i + 1]; };
const cli = option('--cli'); const modelRoot = option('--model-root');
if (!cli || !modelRoot || !path.isAbsolute(cli) || !path.isAbsolute(modelRoot)) throw new Error('Pass absolute --cli and --model-root paths');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'lehrosol-engine-check-'));
process.env.LEHRO_HOME = temp; process.env.LEHROSOL_BIN = cli;
const bridge = require('../electron/bridge');
let port; let started = false;
const checks = [];
(async () => {
  const reservation = net.createServer();
  await new Promise((done) => reservation.listen(0, '127.0.0.1', done)); port = reservation.address().port;
  await new Promise((done) => reservation.close(done));
  const added = await bridge.addVaultRoot(modelRoot); assert.equal(added.ok, true, JSON.stringify(added));
  const vault = await bridge.vault(); assert.equal(vault.ok, true);
  const model = vault.data.models.find((m) => m.id && typeof m.path === 'string' && path.resolve(m.path).startsWith(path.resolve(modelRoot) + path.sep) && !/mmproj|mtp/i.test(m.id));
  assert.ok(model, 'No inference model in this root');
  assert.ok(model.sizeBytes < 1024 * 1024 * 1024, 'This smoke check is bounded to a model smaller than 1 GiB');
  console.log(`Starting actual GGUF ${model.id}`);
  const serve = await bridge.runJson(['vault', 'serve', '--model', model.id, '--port', String(port), '--apiKey', 'engine-check-local', '--ctxSize', '512', '--threads', '2', '--gpuLayers', '0', '--resourceProfile', 'eco', '--json'], 180000);
  assert.equal(serve.ok, true, JSON.stringify(serve).slice(0, 1800)); started = true;
  const health = await bridge.pingServer(port, 'engine-check-local'); assert.equal(health.ok, true);
  checks.push('CLI vault discovery and actual llama-server startup', 'Authenticated engine health');
  const completion = await bridge.chatOnce({ port, apiKey: 'engine-check-local', prompt: 'Say hello in one short sentence.', maxTokens: 8, temperature: 0 });
  assert.equal(completion.ok, true, completion.error); assert.ok(completion.text.length > 0);
  checks.push('Actual GGUF completion'); console.log(`PASS actual completion (${completion.tokens} tokens)`);
  const stop = await bridge.runJson(['serve', 'stop', '--port', String(port), '--json'], 30000); assert.equal(stop.ok, true, JSON.stringify(stop));
  const stopped = await bridge.pingServer(port, 'engine-check-local'); assert.equal(stopped.ok, false); started = false;
  checks.push('CLI engine stop and closed port');
  fs.mkdirSync(path.join(root, 'dist', 'qa'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dist', 'qa', 'engine-check.json'), JSON.stringify({ cliVersion: bridge.cliVersion(), model: model.id, checks, completion: { tokens: completion.tokens, ms: completion.ms, text: completion.text }, scope: 'Small GGUF startup/API/stop only; coding quality and all hardware profiles unverified', at: new Date().toISOString() }, null, 2));
  console.log(`PASS ${checks.length} real-engine checks`);
})().catch((err) => { console.error(err); process.exitCode = 1; }).finally(async () => {
  const state = bridge.serveState().serve;
  if (started || state?.pid) await bridge.runJson(['serve', 'stop', '--port', String(port), '--json'], 30000).catch(() => {});
  if (!path.resolve(temp).startsWith(path.resolve(os.tmpdir()) + path.sep) || !path.basename(temp).startsWith('lehrosol-engine-check-')) throw new Error('Refusing unsafe cleanup');
  fs.rmSync(temp, { recursive: true, force: true });
});
